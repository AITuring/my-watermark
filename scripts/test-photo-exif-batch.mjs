import assert from 'node:assert/strict';
import { build } from 'esbuild';

const result = await build({ stdin: { contents: `export * from './src/pages/photo-exif/actions/item-actions'; export * from './src/pages/photo-exif/missing-info'; export { applySourceMetadataToItem, editableGpsToPoint, isPhotoExifImageName, listDirectoryImageEntries, buildPhotoExifItemsSequentially } from './src/pages/photo-exif/utils'; export { EMPTY_EDITABLE, EMPTY_GPS, DEFAULT_IMPORT_SCOPE_SELECTION } from './src/pages/photo-exif/constants';`, resolveDir: process.cwd() }, bundle: true, write: false, platform: 'node', format: 'esm', packages: 'external', alias: { '@': './src' } });
// Resolve external dependencies relative to this project's scripts directory.
const { writeFile, unlink } = await import('node:fs/promises');
const path = new URL('./.photo-exif-test-bundle.mjs', import.meta.url);
await writeFile(path, result.outputFiles[0].text);
try {
    const m = await import(path.href);
    const item = (fields = {}, gps = m.EMPTY_GPS) => ({ canWriteExif: true, editableCurrent: { ...m.EMPTY_EDITABLE, ...fields }, editableOriginal: { ...m.EMPTY_EDITABLE, ...fields }, gpsOriginal: { ...gps }, gpsCurrent: { ...gps }, summary: {} });
    const existing = item({ artist: '原作者', model: '原相机' }, { enabled: true, lat: '0', lng: '0', locationName: '' });
    const missing = item({ artist: '  ' });
    const values = { ...m.EMPTY_EDITABLE, artist: '新作者', model: '新相机' };
    const gps = { enabled: true, lat: '30', lng: '120', locationName: '地点' };
    let r = m.applyBatchChangesToItems([existing, missing], values, gps, true, null);
    assert.equal(r.affected, 1);
    assert.equal(r.nextItems[0], existing);
    assert.equal(r.nextItems[1].editableCurrent.model, '新相机');
    assert.equal(Number(r.nextItems[1].gpsCurrent.lat), 30);
    r = m.applyBatchChangesToItems([existing], values, m.EMPTY_GPS, false, null, false);
    assert.equal(r.nextItems[0].editableCurrent.model, '新相机');
    assert.equal(r.nextItems[0].gpsCurrent.lat, '0');
    r = m.applyBatchChangesToItems([existing], m.EMPTY_EDITABLE, m.EMPTY_GPS, true, null, false);
    assert.equal(r.nextItems[0].editableCurrent.model, '');
    assert.equal(r.nextItems[0].gpsCurrent.enabled, false);
    const source = item({ artist: '来源作者', software: '软件' }, gps);
    const imported = m.applySourceMetadataToItem(existing, source, m.DEFAULT_IMPORT_SCOPE_SELECTION, true);
    assert.equal(imported.editableCurrent.artist, '原作者');
    assert.equal(imported.editableCurrent.model, '原相机');
    assert.equal(imported.gpsCurrent.lat, '0');
    const scopes = { camera: true, time: true, copyright: true, gps: true, shooting: true };
    const filled = m.applySourceMetadataToItem(missing, source, scopes, true);
    assert.equal(filled.editableCurrent.artist, '来源作者');
    assert.equal(filled.gpsCurrent.lng, '120');
    assert.equal(m.editableGpsToPoint({ enabled: true, lat: '', lng: '' }), null);
    assert.deepEqual(m.editableGpsToPoint(existing.gpsCurrent), { lat: 0, lng: 0 });
    assert.equal(m.applyCopyrightPresetToItems([existing], { artist: '预设作者', copyright: '版权' }).nextItems[0].editableCurrent.artist, '原作者');
    const complete = item({ model: '相机', dateTimeOriginal: '2026:11:21 10:00:00' }, gps);
    const noGps = item({ model: '相机', dateTimeOriginal: '2026:11:21 10:00:00' });
    const noTime = item({ model: '相机' }, gps);
    assert.deepEqual(m.filterPhotoItems([complete, noGps, noTime], 'auto', true), [noGps, noTime]);
    assert.deepEqual(m.filterPhotoItems([complete, noGps, noTime], 'gps', true), [noGps]);
    assert.deepEqual(m.filterPhotoItems([complete, noGps, noTime], 'time', true), [noTime]);
    assert.deepEqual(m.filterPhotoItems([complete, noGps], 'all', true), [complete, noGps]);
    assert.deepEqual(m.filterPhotoItems([complete, noGps], 'auto', false), [complete, noGps]);
    assert.deepEqual(m.filterPhotoItems([complete], 'camera', true), []);
    const gpsOnly = { gps: true, core: false, time: false, copyright: false, description: false };
    const timeOnly = { ...gpsOnly, gps: false, time: true };
    assert.equal(m.hasSourceMetadata(item(), m.DEFAULT_IMPORT_SCOPE_SELECTION), false);
    assert.equal(m.hasSourceMetadata(item({ artist: '   ' }), m.DEFAULT_IMPORT_SCOPE_SELECTION), false);
    assert.equal(m.hasSourceMetadata(complete, gpsOnly), true);
    assert.equal(m.hasSourceMetadata(noGps, gpsOnly), false);
    assert.equal(m.hasSourceMetadata(noTime, timeOnly), false);
    assert.equal(m.hasSourceMetadata(noGps, timeOnly), true);
    assert.equal(m.hasSourceMetadata(item({ artist: '作者' }), m.DEFAULT_IMPORT_SCOPE_SELECTION), true);
    assert.equal(m.hasSourceMetadata(complete, { ...gpsOnly, gps: false }), false);
    assert.equal(m.hasSourceMetadata(item({}, { enabled: true, lat: '', lng: '120', locationName: '地点' }), gpsOnly), false);
    const pending = { ...complete, editableOriginal: { ...complete.editableOriginal, model: '' } };
    assert.deepEqual(m.filterPhotoItems([complete, pending], 'auto', true), [pending]);
    assert.deepEqual(m.filterPhotoItems([complete, pending], 'gps', true), [pending]);
    assert.deepEqual(m.filterPhotoItems([complete, pending], 'pending', true), [pending]);
    assert.equal(m.isPhotoExifImageName('._良渚文化-玉琮.jpg'), false);
    assert.equal(m.isPhotoExifImageName('目录/._DSC00598-1.JPG'), false);
    assert.equal(m.isPhotoExifImageName('__MACOSX/DSC00598.jpg'), false);
    assert.equal(m.isPhotoExifImageName('良渚文化-玉琮.jpg'), true);
    assert.equal(m.isPhotoExifImageName('DSC00598.JPG'), true);
    const photoFile = { name: 'DSC00598.jpg', size: 10 };
    const directory = { async *values() {
        yield { kind: 'file', name: '._DSC00598.jpg', getFile() { throw new Error('Sidecars must not be read'); } };
        yield { kind: 'file', name: photoFile.name, async getFile() { return photoFile; } };
        yield { kind: 'directory', name: 'folder.jpg' };
    } };
    const directoryEntries = await m.listDirectoryImageEntries(directory);
    assert.equal(directoryEntries.length, 1);
    assert.equal(directoryEntries[0].file, photoFile);
    assert.deepEqual(await m.buildPhotoExifItemsSequentially([{ file: { name: '._DSC00598.jpg' } }], {}), []);
    console.log('Photo EXIF batch regression checks passed');
} finally {
    await unlink(path);
}
