import fs from 'node:fs';
import ts from 'typescript';
import assert from 'node:assert/strict';
const source=fs.readFileSync(new URL('../src/pages/people-sort/onnx-math.ts',import.meta.url),'utf8');
const compiled=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText;
const {similarity,FACE_TEMPLATE,planarRGB,decodeYuNet,suppress,normalizeFeature}=await import(`data:text/javascript;base64,${Buffer.from(compiled).toString('base64')}`);
const identity=similarity(FACE_TEMPLATE);
assert.ok(Math.abs(identity.a-1)<1e-9 && Math.abs(identity.b)<1e-9 && Math.abs(identity.tx)<1e-9);
const transformed=FACE_TEMPLATE.map((v,i)=>v*2+(i%2?20:10));
const inverse=similarity(transformed);
assert.ok(Math.abs(inverse.a-.5)<1e-8 && Math.abs(inverse.tx+5)<1e-8 && Math.abs(inverse.ty+10)<1e-8);
const rotated=[];
for(let i=0;i<10;i+=2)rotated.push(-FACE_TEMPLATE[i+1]+150,FACE_TEMPLATE[i]+30);
const rotation=similarity(rotated);
for(let i=0;i<10;i+=2){assert.ok(Math.abs(rotation.a*rotated[i]-rotation.b*rotated[i+1]+rotation.tx-FACE_TEMPLATE[i])<1e-6);assert.ok(Math.abs(rotation.b*rotated[i]+rotation.a*rotated[i+1]+rotation.ty-FACE_TEMPLATE[i+1])<1e-6);}
assert.deepEqual([...planarRGB(new Uint8ClampedArray([10,20,30,255]),true)],[30,20,10]);
assert.deepEqual([...planarRGB(new Uint8ClampedArray([10,20,30,255]))],[10,20,30]);
assert.throws(()=>similarity(Array(10).fill(0)));
const outputs={};
for(const stride of [8,16,32])for(const [name,mult]of [['cls',1],['obj',1],['bbox',4],['kps',10]])outputs[`${name}_${stride}`]={data:new Float32Array((640/stride)**2*mult)};
const i=10*80+10;
outputs.cls_8.data[i]=.9;outputs.obj_8.data[i]=.9;
outputs.bbox_8.data[i*4+2]=Math.log(10);outputs.bbox_8.data[i*4+3]=Math.log(10);
const decoded=decodeYuNet(outputs);
assert.equal(decoded.length,1);assert.ok(Math.abs(decoded[0].width-80)<1e-4);assert.ok(Math.abs(decoded[0].x-40)<1e-4);
assert.equal(suppress([decoded[0],{...decoded[0],score:.8}]).length,1);
const feature=normalizeFeature(Array(128).fill(2));
assert.ok(Math.abs(feature.reduce((sum,v)=>sum+v*v,0)-1)<1e-9);
assert.throws(()=>normalizeFeature(Array(128).fill(0)));
console.log('ONNX preprocessing, YuNet decoding/NMS, alignment and feature normalization passed');
