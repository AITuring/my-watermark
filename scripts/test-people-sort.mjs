import { readFileSync } from 'node:fs';
import ts from 'typescript';
import assert from 'node:assert/strict';
const source = readFileSync(new URL('../src/pages/people-sort/grouping.ts', import.meta.url), 'utf8');
const { outputText } = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } });
const { groupFaces, uniqueName, safeName } = await import(`data:text/javascript;base64,${Buffer.from(outputText).toString('base64')}`);
const groups = groupFaces([{id:'a',descriptor:[0,0]}, {id:'b',descriptor:[0.1,0]}, {id:'c',descriptor:[1,1]}, {id:'d'}, {id:'e',descriptor:[0.2,0]}],0.48);
assert.deepEqual(groups.map(g => g.photoIds), [['a','b','e'],['c'],['d']]);
// Complete linkage prevents a series of near matches from joining distinct endpoints.
assert.deepEqual(groupFaces([{id:'a',descriptor:[0]}, {id:'b',descriptor:[0.4]}, {id:'c',descriptor:[0.8]}],0.5).map(g=>g.photoIds),[['a','b'],['c'],[]]);
const used = new Set();
assert.equal(uniqueName('DSC001.jpg',used),'DSC001.jpg');
assert.equal(uniqueName('DSC001.jpg',used),'DSC001 (2).jpg');
assert.equal(uniqueName('dsc001.JPG',used),'dsc001 (3).JPG');
assert.equal(safeName('../人物/一'), '.._人物_一');
assert.equal(safeName('..'),'未命名');
assert.deepEqual(groupFaces([],0.48).map(g=>g.photoIds),[[]]);
console.log('people-sort grouping and export naming checks passed');
const detectionSource = readFileSync(new URL('../src/pages/people-sort/detection.ts', import.meta.url), 'utf8');
const compiled = ts.transpileModule(detectionSource, { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } });
const { primaryFace, faceCrop } = await import(`data:text/javascript;base64,${Buffer.from(compiled.outputText).toString('base64')}`);
const face = (width, height, score = 0.9) => ({ box: { x: 10, y: 10, width, height }, score });
const subject = face(100,120);
assert.equal(primaryFace([face(20,25), subject]), subject, 'ignore a clearly smaller background face');
assert.equal(primaryFace([subject, face(90,110)]), undefined, 'do not choose arbitrarily among two subjects');
assert.equal(primaryFace([face(100,120,0.3)]), undefined, 'reject weak false detections');
assert.equal(primaryFace([face(35,40)]).box.width,35,'keep small faces for original-resolution refinement');
assert.deepEqual(faceCrop({x:0,y:0,width:100,height:100},120,110),{x:0,y:0,width:120,height:110});
console.log('primary subject selection and original crop bounds checks passed');
const { matchReferences } = await import(`data:text/javascript;base64,${Buffer.from(outputText).toString('base64')}`);
assert.equal(matchReferences({id:'x',descriptor:[0.1,0]},[{groupId:'a',descriptors:[[0,0]]},{groupId:'b',descriptors:[[1,1]]}],0.48),'a');
assert.equal(matchReferences({id:'x',descriptor:[0.1,0]},[{groupId:'a',descriptors:[[0,0]]},{groupId:'b',descriptors:[[0.2,0]]}],0.48),undefined);
assert.equal(matchReferences({id:'x'},[{groupId:'a',descriptors:[[0,0]]}],0.48),undefined);
console.log('reference matching: known identity, ambiguity and missing face checks passed');
